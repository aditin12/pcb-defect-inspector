"""Central config for the PCB defect detection pipeline."""
import os

ML_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))     # .../ml
PROJECT_ROOT = os.path.dirname(ML_ROOT)                                    # repo root

DATA_DIR = os.path.join(ML_ROOT, "data")
RAW_DIR = os.path.join(DATA_DIR, "raw")            # expects images/ + Annotations/ (VOC XML) after download
YOLO_DATA_DIR = os.path.join(DATA_DIR, "yolo")      # generated by prepare_data.py

MODELS_DIR = os.path.join(PROJECT_ROOT, "models")
RESULTS_DIR = os.path.join(PROJECT_ROOT, "results")
os.makedirs(MODELS_DIR, exist_ok=True)
os.makedirs(RESULTS_DIR, exist_ok=True)

# Class order matters: it must match data.yaml and stay fixed across train/eval/inference.
CLASS_NAMES = [
    "missing_hole",
    "mouse_bite",
    "open_circuit",
    "short",
    "spur",
    "spurious_copper",
]
NUM_CLASSES = len(CLASS_NAMES)

# Rule-based severity engine weights (see severity.py for rationale).
# Higher = more critical to a functioning board.
DEFECT_CRITICALITY = {
    "short": 1.0,           # can damage the board / connected components -- most critical
    "open_circuit": 0.9,    # breaks the intended circuit path
    "missing_hole": 0.7,    # breaks connectivity where a via/pad was expected
    "mouse_bite": 0.5,      # weakens a trace, may not break it outright
    "spur": 0.35,           # excess copper, risk of unintended short if it grows/shifts
    "spurious_copper": 0.35,
}

TRAIN_SPLIT = 0.70
VAL_SPLIT = 0.15
TEST_SPLIT = 0.15
SPLIT_SEED = 42

IMAGE_SIZE = 640          # YOLOv8 default input resolution
EPOCHS = 80
BATCH_SIZE = 16
BASE_MODEL = "yolov8n.pt"  # nano: trains fast on CPU/laptop GPU; swap to yolov8s.pt for more accuracy
